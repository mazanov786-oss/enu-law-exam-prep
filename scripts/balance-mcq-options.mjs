// Map of specific question text matches to scenario
function getScenarioForQuestion(q) {
  const t = q.text.toLowerCase();
  if (q.subject === "up") {
    if (t.includes("вина") || t.includes("умысел") || t.includes("неосторожн")) return balancedHardScenarios.guilt;
    if (t.includes("стадии") || t.includes("приготовлен") || t.includes("покушен")) return balancedHardScenarios.stages;
    if (t.includes("соучасти") || t.includes("эксцесс")) return balancedHardScenarios.complicity;
    if (t.includes("необходим") && t.includes("оборон")) return balancedHardScenarios.defense;
    if (t.includes("крайн") && t.includes("необходимост")) return balancedHardScenarios.necessity;
    if (t.includes("зачет") || t.includes("страж")) return balancedHardScenarios.detention;
    if (t.includes("совокупност") && t.includes("преступлен")) return balancedHardScenarios.sentencing;
  } else {
    if (t.includes("недействительн") && t.includes("сделк")) return balancedHardScenarios.civilInvalidity;
    if (t.includes("гарант") || t.includes("поручительств")) return balancedHardScenarios.civilGuarantee;
    if (t.includes("форма") && t.includes("сделок")) return balancedHardScenarios.civilForm;
  }
  return null;
}

// Giveaway parentheticals and phrases to clean from options
const giveawayParentheticalRegex = /\s*\((презумпция невиновности|частное предупреждение|общее предупреждение|формально-юридический|нормотворческая|запрет объективного вменения|определяемый объектом|компенсация|эксцесс исполнителя|казус|легкомыслие|от слова[^)]+|подобно[^)]+|как в[^)]+|ч\.\s*\d+[^)]*|ст\.\s*\d+[^)]*|п\.\s*\d+[^)]*|поскольку[^)]+|так как[^)]+|включая[^)]+|например[^)]+|применяются[^)]+|срокам[^)]+)\)/gi;

const trailingReasonRegex = /,\s*(так как|поскольку|в силу того что|ввиду того что)\s+.+$/i;

let genericRemoved = 0;
let parentheticalsCleaned = 0;
let reasonsTrimmed = 0;
let totalMcqs = 0;

for (const q of db.questions) {
  // 1. Remove generic fallback questions
  const initialCount = q.mcq ? q.mcq.length : 0;
  q.mcq = (q.mcq || []).filter(
    (m) =>
      !m.q.includes("какое юридическое толкование норм") &&
      !m.q.includes("какое толкование является определяющим") &&
      !m.q.includes("Неукоснительное соблюдение буквального смысла")
  );
  genericRemoved += initialCount - q.mcq.length;

  // 2. If matching scenario exists, prepend balanced scenarios
  const scenario = getScenarioForQuestion(q);
  if (scenario) {
    // Check if already present to avoid duplication
    for (const sc of scenario) {
      const exists = q.mcq.some((m) => m.q === sc.q);
      if (!exists) {
        q.mcq.unshift(JSON.parse(JSON.stringify(sc)));
      }
    }
  }

  // 3. Clean options in all MCQs
  for (const m of q.mcq) {
    totalMcqs++;

    m.options = m.options.map((opt) => {
      let cleaned = opt.replace(giveawayParentheticalRegex, "").trim();
      if (cleaned !== opt) parentheticalsCleaned++;
      // remove standalone unnecessary brackets
      cleaned = cleaned.replace(/\s*\(\s*\)/g, "").trim();
      return cleaned;
    });

    // Trim trailing reasons in correct answer if distractors don't have reasons
    const c = m.options[m.correct];
    const othersHaveReason = m.options.some(
      (o, i) => i !== m.correct && trailingReasonRegex.test(o)
    );
    if (c && trailingReasonRegex.test(c) && !othersHaveReason) {
      const trimmed = c.replace(trailingReasonRegex, "").trim();
      if (trimmed.length >= 15) {
        m.options[m.correct] = trimmed;
        reasonsTrimmed++;
      }
    }

    // 4. Uniform position shuffle for static data
    // Deterministic shuffle of options so correct index is evenly distributed 0..3 (~25% each)
    const currentCorrectText = m.options[m.correct];
    const optsWithFlag = m.options.map((text, idx) => ({
      text: text.replace(/\s*\(ничтожность\)/gi, "").replace(/\s{2,}/g, " ").trim(),
      isCorrect: idx === m.correct,
    }));

    // Hash-based deterministic rotation/shuffle
    let h = 0;
    const key = `${q.id}-${m.q}`;
    for (let k = 0; k < key.length; k++) {
      h = (h << 5) - h + key.charCodeAt(k);
      h |= 0;
    }
    for (let i = optsWithFlag.length - 1; i > 0; i--) {
      const j = Math.floor(Math.abs(Math.sin(h * 31 + i * 19)) * (i + 1));
      [optsWithFlag[i], optsWithFlag[j]] = [optsWithFlag[j], optsWithFlag[i]];
    }

    m.options = optsWithFlag.map((o) => o.text);
    m.correct = optsWithFlag.findIndex((o) => o.isCorrect);
  }
}

console.log(`Phase 1 Complete:`);
console.log(`- Removed ${genericRemoved} generic fallback MCQs`);
console.log(`- Cleaned ${parentheticalsCleaned} giveaway parentheticals`);
console.log(`- Trimmed ${reasonsTrimmed} trailing reason clauses`);
console.log(`- Total active MCQs remaining: ${totalMcqs}`);

// Write intermediate clean version
fs.writeFileSync(examDataPath, JSON.stringify(db, null, 2), "utf8");
