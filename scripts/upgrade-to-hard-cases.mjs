// Assign case studies matching questions
let assignedCasesCount = 0;
let hardQuestionsCount = 0;

for (let i = 0; i < examDb.questions.length; i++) {
  const q = examDb.questions[i];
  const t = q.text.toLowerCase();
  let assignedCase = null;

  if (q.subject === "up") {
    if (t.includes("действие") && t.includes("времен")) {
      assignedCase = hardCasesDatabase["up-operation-in-time"];
    } else if (t.includes("стади") || t.includes("покушен") || t.includes("приготовлен") || t.includes("отказ")) {
      assignedCase = hardCasesDatabase["up-stages"];
    } else if (t.includes("соучаст") || t.includes("эксцесс") || t.includes("групп")) {
      assignedCase = hardCasesDatabase["up-complicity"];
    } else if (t.includes("оборон") || t.includes("необходим")) {
      assignedCase = hardCasesDatabase["up-defense"];
    } else if (t.includes("крайн") && t.includes("необходимост")) {
      assignedCase = hardCasesDatabase["up-necessity"];
    } else if (t.includes("зачет") || t.includes("страж") || t.includes("лишен")) {
      assignedCase = hardCasesDatabase["up-pretrial-detention"];
    } else if (t.includes("совокупност") || t.includes("назначен")) {
      assignedCase = hardCasesDatabase["up-sentencing-multiple"];
    } else if (t.includes("давность") || t.includes("освобожден")) {
      assignedCase = hardCasesDatabase["up-statute-limitations"];
    }
  } else {
    // gp
    if (t.includes("безвестн") || t.includes("умерш") || t.includes("граждан")) {
      assignedCase = hardCasesDatabase["gp-absence-death"];
    } else if (t.includes("филиал") || t.includes("представительств") || t.includes("лиц")) {
      assignedCase = hardCasesDatabase["gp-legal-entities-branches"];
    } else if (t.includes("виндикац") || t.includes("собственност") || t.includes("вещн")) {
      assignedCase = hardCasesDatabase["gp-vindication"];
    } else if (t.includes("гарант") || t.includes("поручительств") || t.includes("обеспечен")) {
      assignedCase = hardCasesDatabase["gp-guarantee-suretyship"];
    } else if (t.includes("недействительн") || t.includes("сделк")) {
      assignedCase = hardCasesDatabase["gp-invalidity-threat"];
    } else if (t.includes("неустойк") || t.includes("убытк") || t.includes("ответственност")) {
      assignedCase = hardCasesDatabase["gp-penalty-losses"];
    }
  }

  // If matched or fallback representative case for modules
  if (!assignedCase) {
    if (q.subject === "up") {
      assignedCase = q.module === 1 ? hardCasesDatabase["up-stages"] : hardCasesDatabase["up-pretrial-detention"];
    } else {
      assignedCase = q.module === 1 ? hardCasesDatabase["gp-absence-death"] : hardCasesDatabase["gp-vindication"];
    }
  }

  q.caseStudy = assignedCase;
  assignedCasesCount++;

  // Upgrade or prepend hard-level scenario MCQs
  const hardMcqs = createHardMcqsForQuestion(q);
  // Mark existing mcqs
  q.mcq = q.mcq || [];
  // Prepend hard MCQs so they appear first and test real skills
  q.mcq = [...hardMcqs, ...q.mcq];
  // Deduplicate by question text
  const seenQ = new Set();
  q.mcq = q.mcq.filter((m) => {
    if (seenQ.has(m.q)) return false;
    seenQ.add(m.q);
    return true;
  });

  hardQuestionsCount++;
}

